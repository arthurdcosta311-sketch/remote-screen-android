#!/bin/bash
# Builds the adb-mobile static library for iphoneos/arm64 and turns the ADB
# bridge on for the Xcode project.
#
#   ./tools/build-adb.sh
#
# On success it writes ios/Adb.xcconfig.generated, which the release workflow
# copies over ios/Adb.xcconfig. On failure nothing is written, so the app still
# builds — just without the bridge.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/adb-mobile-adb_v31.0.3"
OUT="$ROOT/ios/adb"
XCCONFIG="$ROOT/ios/Adb.xcconfig.generated"

say() { printf '\n== %s\n' "$1"; }

clone() {
    local dir="$1" url="$2"
    if [[ -d "$dir/.git" ]]; then
        return 0
    fi
    say "cloning $(basename "$dir")"
    git clone --depth 1 --recursive "$url" "$dir"
}

say "adb sources"
clone "$SRC/android-tools" "https://github.com/nmeum/android-tools.git"
clone "$SRC/ios-cmake" "https://github.com/leetal/ios-cmake.git"
clone "$SRC/external/lz4" "https://android.googlesource.com/platform/external/lz4"
clone "$SRC/external/zstd" "https://android.googlesource.com/platform/external/zstd"
clone "$SRC/external/brotli" "https://android.googlesource.com/platform/external/brotli"
clone "$SRC/external/protobuf" "https://github.com/protocolbuffers/protobuf.git"

say "protoc 3.19.4"
if ! protoc --version 2>/dev/null | grep -q '3\.19\.4'; then
    work="$(mktemp -d)"
    curl -fsSL -o "$work/protobuf.tar.gz" \
        https://github.com/protocolbuffers/protobuf/releases/download/v3.19.4/protobuf-all-3.19.4.tar.gz
    tar -xzf "$work/protobuf.tar.gz" -C "$work"
    (
        cd "$work/protobuf-3.19.4"
        ./configure --disable-shared --prefix="$work/install"
        make -j8 protoc
        mkdir -p "$work/install/bin"
        install -m755 src/protoc "$work/install/bin/protoc"
    )
    export PATH="$work/install/bin:$PATH"
fi
protoc --version

say "libadb for iphoneos/arm64"
rm -rf "$SRC/output"
mkdir -p "$SRC/output/iphoneos/arm64"
make -C "$SRC/porting" \
    lz4/iphoneos/arm64 \
    zstd/iphoneos/arm64 \
    brotli/iphoneos/arm64 \
    protobuf/iphoneos/arm64 \
    adb/iphoneos/arm64
libtool -static -o "$SRC/output/libadb-iphoneos-arm64.a" "$SRC/output/iphoneos/arm64/"*.a

say "assembling ios/adb"
mkdir -p "$OUT/lib" "$OUT/include"
cp "$SRC/output/libadb-iphoneos-arm64.a" "$OUT/lib/"
cp "$SRC/output/include/"*.h "$OUT/include/"

say "writing $XCCONFIG"
cat > "$XCCONFIG" <<'CFG'
// Generated by tools/build-adb.sh: the adb bridge is compiled into this build.
GCC_PREPROCESSOR_DEFINITIONS = $(inherited) ADB_MOBILE=1
SWIFT_ACTIVE_COMPILATION_CONDITIONS = $(inherited) ADB_MOBILE
LIBRARY_SEARCH_PATHS = $(inherited) $(SRCROOT)/adb/lib
OTHER_LDFLAGS = $(inherited) -ladb-iphoneos-arm64 -lc++ -lz
CFG
echo "done: $(du -h "$OUT/lib/libadb-iphoneos-arm64.a" | cut -f1)"
